export interface InitOptions {
  projectRoot: string;
  force?: boolean;
  /** Place memory, changes, domains, and archive beneath this project-relative root. */
  layoutRoot?: string;
  /**
   * AI coding agent to install (single, Speckit-style). Not an IDE.
   * - omit / `false` — no agent files
   * - `AgentTarget` — install that integration only
   */
  agents?: false | AgentTarget;
  /**
   * Test seam for "is this path tracked?". Return null when git cannot answer.
   * Production uses `git ls-files`.
   */
  indexLookup?: (projectRoot: string, relativePaths: string[]) => Promise<string[] | null>;
}

export interface InitResult {
  created: string[];
  config: Config;
  warnings: string[];
  /** Existing files init left alone: not generated by sdd, or edited since */
  kept: KeptFile[];
  agents?: { created: string[]; skipped: string[]; kept: KeptFile[]; removed: string[] };
}

export async function initProject(opts: InitOptions): Promise<InitResult> {
  const { projectRoot, force = false } = opts;
  const created: string[] = [];
  const kept: KeptFile[] = [];
  const warnings: string[] = [];
  const root = sddRoot(projectRoot);
  const configFile = join(root, "config.yaml");

  if ((await pathExists(configFile)) && !force) {
    await repairRequiredIgnores(projectRoot);
    return { created, config: await loadConfig(projectRoot), kept, warnings };
  }

  // Check before writing anything, so a bad path cannot leave .sdd/ half-written.
  try {
    const st = await lstat(root);
    if (!st.isDirectory() && !st.isSymbolicLink()) {
      throw new SddError(`Cannot initialize: ${root} exists and is not a directory. Move it away.`);
    }
  } catch (err) {
    if (err instanceof SddError) throw err;
  }

  const config = (await pathExists(configFile))
    ? mergeConfigDefaults(await readYaml(configFile))
    : defaultConfig();
  if (opts.layoutRoot !== undefined) {
    const layoutRoot = validateLayoutRoot(opts.layoutRoot);
    config.memory_path = join(layoutRoot, "memory");
    config.changes_path = join(layoutRoot, "changes");
    config.domains_path = join(layoutRoot, "domains");
    config.archive_path = join(layoutRoot, "archive");
  }
  const manifestPath = join(root, ".generated.json");
  const manifestExisted = await pathExists(manifestPath);
  const manifest = await loadGeneratedManifest(manifestPath);

  if (opts.agents) {
    await assertAgentInstallable({ projectRoot, target: opts.agents, force });
  }

  await ensureDir(root);
  await saveConfig(projectRoot, config);
  created.push(join(root, "config.yaml"));

  // workflows
  const wfDest = workflowsDir(projectRoot);
  const wfSrc = defaultWorkflowsDir();
  if (await pathExists(wfSrc)) {
    const result = await reconcileGeneratedTree(
      projectRoot,
      wfSrc,
      wfDest,
      ".sdd/workflows",
      manifest,
      force,
    );
    kept.push(...result.kept);
    created.push(wfDest);
  } else {
    await ensureDir(wfDest);
  }

  // templates
  const tDest = templatesDir(projectRoot);
  const tSrc = defaultTemplatesDir();
  if (await pathExists(tSrc)) {
    const result = await reconcileGeneratedTree(
      projectRoot,
      tSrc,
      tDest,
      ".sdd/templates",
      manifest,
      force,
    );
    kept.push(...result.kept);
    created.push(tDest);
  } else {
    await ensureDir(tDest);
  }
  await saveGeneratedManifest(manifestPath, manifest);
  if (!manifestExisted) created.push(manifestPath);

  // external MCP sources config (sdd as client — org libs, AST engines, …)
  const mcpSrc = defaultMcpYamlPath();
  const mcpDest = mcpConfigPath(projectRoot);
  if (await pathExists(mcpSrc)) {
    const wrote = await writeTextIfMissing(mcpDest, await readText(mcpSrc));
    if (wrote) created.push(mcpDest);
  }

  // Operator-owned prices. Write only when missing, including on --force.
  const pricesSrc = defaultPricesYamlPath();
  const pricesDest = join(root, "prices.yaml");
  if (await pathExists(pricesSrc)) {
    const wrote = await writeTextIfMissing(pricesDest, await readText(pricesSrc));
    if (wrote) created.push(pricesDest);
  }

  // Operator-owned search config. Same write-if-missing rule as prices.yaml.
  const searchSrc = defaultSearchYamlPath();
  const searchDest = join(root, "search.yaml");
  if (await pathExists(searchSrc)) {
    const wrote = await writeTextIfMissing(searchDest, await readText(searchSrc));
    if (wrote) created.push(searchDest);
  }

  // memory — stable team docs; never overwrite on --force (constitution, product, …)
  const mDest = memoryDir(projectRoot, config);
  const existingMemoryFiles = await listRelativeFiles(mDest);
  if (existingMemoryFiles.length && config.memory_path === "memory") {
    warnings.push(
      `Existing ${config.memory_path}/ content will be preserved. Use --root .sdd to keep SDD memory alongside the project without merging folders.`,
    );
  }
  await ensureDir(mDest);
  const mSrc = defaultMemoryDir();
  if (await pathExists(mSrc)) {
    await copyDirSkipExisting(mSrc, mDest);
  } else {
    await writeTextIfMissing(
      join(mDest, "index.md"),
      `# Documentation map

Parent page for **stable** project docs. Start here, then open only what you need.

| Topic | File |
|-------|------|
| Product | [product.md](product.md) |
| Constitution (non-negotiables) | [constitution.md](constitution.md) |
| Architecture | [architecture.md](architecture.md) |
| Conventions | [conventions.md](conventions.md) |

Active work: \`.sdd/active-context.md\` and the configured changes folder.
`,
    );
    await writeTextIfMissing(
      join(mDest, "product.md"),
      "# Product\n\n<!-- What are you building? -->\n",
    );
    await writeTextIfMissing(
      join(mDest, "constitution.md"),
      `# Constitution

<!-- Non-negotiables agents must not violate. Broader style lives in conventions.md. -->

## Principles

-

## Stack & tooling

-

## Testing

-

## Security

-

## Process

-
`,
    );
    await writeTextIfMissing(
      join(mDest, "architecture.md"),
      "# Architecture\n\n<!-- High-level system shape -->\n",
    );
    await writeTextIfMissing(
      join(mDest, "conventions.md"),
      "# Conventions\n\n<!-- Coding and process conventions -->\n",
    );
  }
  // Ensure constitution exists even for older projects re-initing (add if missing only)
  if (!(await pathExists(join(mDest, "constitution.md")))) {
    const fromDefault = join(mSrc, "constitution.md");
    if (await pathExists(fromDefault)) {
      await copyDirSkipExisting(mSrc, mDest);
    } else {
      await writeTextIfMissing(
        join(mDest, "constitution.md"),
        `# Constitution

<!-- Non-negotiables agents must not violate. Broader style lives in conventions.md. -->

## Principles

-

## Stack & tooling

-

## Testing

-

## Security

-

## Process

-
`,
      );
    }
  }
  created.push(mDest);

  await ensureDir(changesDir(projectRoot, config));
  await ensureDir(domainsDir(projectRoot, config));
  created.push(changesDir(projectRoot, config));
  created.push(domainsDir(projectRoot, config));
  // archive/ is not scaffolded by default; created only when a complete actually archives

  // gitkeep style
  await writeTextIfMissing(join(changesDir(projectRoot, config), ".gitkeep"), "");
  await writeTextIfMissing(join(domainsDir(projectRoot, config), ".gitkeep"), "");

  const sddIgnore = join(root, ".gitignore");
  const changesIgnore = join(changesDir(projectRoot, config), ".gitignore");
  if ((await ensureIgnoreEntries(sddIgnore, SDD_IGNORE_LINES)).created) {
    created.push(sddIgnore);
  }
  if ((await ensureIgnoreEntries(changesIgnore, [".active"])).created) {
    created.push(changesIgnore);
  }
  const perMachine = [
    ".sdd/active-context.md",
    ".sdd/handoff.md",
    ".sdd/index.db",
    `${changesPathRel(config)}/.active`,
  ];
  const tracked = await (opts.indexLookup ?? gitTrackedPaths)(projectRoot, perMachine);
  if (tracked) {
    for (const rel of tracked) {
      warnings.push(
        `Already tracked (gitignore will not hide edits): ${rel}. sdd does not run git rm.`,
      );
    }
  }

  // root pointer README for humans
  const sddReadme = join(root, "README.md");
  const readmeState = (await pathExists(sddReadme))
    ? generatedState(await readText(sddReadme))
    : null;
  if (readmeState === "edited" || readmeState === "not-generated") {
    kept.push({ path: ".sdd/README.md", reason: readmeState });
  } else if (readmeState === null || force) {
    await writeText(sddReadme, markGenerated(renderSddReadme(config)));
    created.push(sddReadme);
  }

  let agentsResult: InitResult["agents"];
  if (opts.agents) {
    const ag = await installAgentIntegration({
      projectRoot,
      target: opts.agents,
      force,
    });
    created.push(...ag.created);
    kept.push(...ag.kept);
    agentsResult = { created: ag.created, skipped: ag.skipped, kept: ag.kept, removed: ag.removed };
  }

  return { created, config, kept, warnings, agents: agentsResult };
}

const SDD_IGNORE_LINES = [
  "handoff.md",
  "active-context.md",
  "index.db",
  "index.db-journal",
  "index.db-wal",
  "index.db-shm",
  "models/",
  "role-runs/",
];

/** Append missing required ignore lines. Does not rewrite config, memory, or workflows. */
export async function repairRequiredIgnores(projectRoot: string): Promise<boolean> {
  const config = await loadConfig(projectRoot);
  const root = sddRoot(projectRoot);
  const sdd = await ensureIgnoreEntries(join(root, ".gitignore"), SDD_IGNORE_LINES);
  const changes = await ensureIgnoreEntries(join(changesDir(projectRoot, config), ".gitignore"), [
    ".active",
  ]);
  return sdd.added || changes.added;
}

/** Append missing ignore lines. `created` is true when the file did not exist before. */
async function ensureIgnoreEntries(
  filePath: string,
  required: string[],
): Promise<{ created: boolean; added: boolean }> {
  const existed = await pathExists(filePath);
  const original = existed ? await readText(filePath) : "";
  const present = new Set(
    original
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter((line) => line.length > 0 && !line.startsWith("#")),
  );
  const missing = required.filter((line) => !present.has(line));
  if (existed && missing.length === 0) return { created: false, added: false };
  let next = original;
  if (next.length > 0 && !next.endsWith("\n")) next += "\n";
  next += missing.map((line) => `${line}\n`).join("");
  await writeText(filePath, next);
  return { created: !existed, added: missing.length > 0 };
}

function gitTrackedPaths(projectRoot: string, relativePaths: string[]): Promise<string[] | null> {
  return new Promise((resolve) => {
    const child = spawn("git", ["ls-files", "--", ...relativePaths], {
      cwd: projectRoot,
      stdio: ["ignore", "pipe", "pipe"],
    });
    let stdout = "";
    child.stdout?.on("data", (chunk: Buffer) => {
      stdout += chunk.toString();
    });
    child.on("error", () => resolve(null));
    child.on("close", (code) => {
      if (code !== 0) resolve(null);
      else
        resolve(
          stdout
            .split(/\r?\n/)
            .map((line) => line.trim())
            .filter(Boolean),
        );
    });
  });
}

function validateLayoutRoot(value: string): string {
  const root = value.trim();
  const segments = root.split(/[\\/]+/);
  if (
    !root ||
    root !== value ||
    root.startsWith("/") ||
    root.startsWith("\\") ||
    /^[A-Za-z]:/.test(root) ||
    segments.some((segment) => segment === ".." || segment === "")
  ) {
    throw new Error("--root must be a non-empty, project-relative path without '..' segments.");
  }
  return segments.join("/");
}

async function listRelativeFiles(directory: string, prefix = ""): Promise<string[]> {
  if (!(await pathExists(directory))) return [];
  const files = (await listFiles(directory)).map((name) =>
    [prefix, name].filter(Boolean).join("/"),
  );
  const nested = await Promise.all(
    (await listDirs(directory)).map((name) =>
      listRelativeFiles(join(directory, name), [prefix, name].filter(Boolean).join("/")),
    ),
  );
  return [...files, ...nested.flat()];
}
